#!/usr/bin/env python3
"""Write a 5x5 grid of UV spheres as OBJ/MTL for checking the PBR BRDF.

Rows go from dielectric (bottom, Pm 0) to metal (top, Pm 1); columns from smooth
(left, Pr 0.05) to rough (right, Pr 1). Each sphere has its own material using
the MTL PBR extension keys Pm / Pr, which the engine's loader reads.

usage: tools/make_sphere_grid.py <out.obj> [rows] [cols]
"""
import math
import sys
from pathlib import Path

SEGMENTS, RINGS = 32, 16
RADIUS, SPACING = 0.4, 1.0
BASE_COLOR = (0.95, 0.64, 0.54)  # copper-like, so metals are visibly tinted


def main():
    out = Path(sys.argv[1])
    rows = int(sys.argv[2]) if len(sys.argv) > 2 else 5
    cols = int(sys.argv[3]) if len(sys.argv) > 3 else 5
    v, vn, faces, mtl = [], [], [], []
    for r in range(rows):
        metallic = r / (rows - 1)
        for c in range(cols):
            roughness = max(0.05, c / (cols - 1))
            name = f"m{metallic:.2f}_r{roughness:.2f}"
            mtl.append(f"newmtl {name}\nKd {BASE_COLOR[0]} {BASE_COLOR[1]} {BASE_COLOR[2]}\n"
                       f"Ka 1 1 1\nKs 0.5 0.5 0.5\nNs 32\nPm {metallic:.3f}\nPr {roughness:.3f}\n")
            cx, cy = (c - (cols - 1) / 2) * SPACING, (r - (rows - 1) / 2) * SPACING
            base = len(v)
            for i in range(RINGS + 1):
                theta = math.pi * i / RINGS
                for j in range(SEGMENTS + 1):
                    phi = 2 * math.pi * j / SEGMENTS
                    n = (math.sin(theta) * math.cos(phi), math.cos(theta), math.sin(theta) * math.sin(phi))
                    v.append((cx + RADIUS * n[0], cy + RADIUS * n[1], RADIUS * n[2]))
                    vn.append(n)
            lines = [f"usemtl {name}"]
            for i in range(RINGS):
                for j in range(SEGMENTS):
                    a = base + i * (SEGMENTS + 1) + j + 1
                    b, cc, d = a + 1, a + SEGMENTS + 2, a + SEGMENTS + 1
                    # Skip the degenerate triangle at each pole.
                    if i != 0:
                        lines.append(f"f {a}//{a} {cc}//{cc} {b}//{b}")
                    if i != RINGS - 1:
                        lines.append(f"f {a}//{a} {d}//{d} {cc}//{cc}")
            faces.append("\n".join(lines))
    with open(out, "w") as f:
        f.write(f"# {rows}x{cols} PBR test spheres, generated by tools/make_sphere_grid.py\n")
        f.write(f"mtllib {out.with_suffix('.mtl').name}\n")
        f.write("\n".join("v %.5f %.5f %.5f" % p for p in v) + "\n")
        f.write("\n".join("vn %.5f %.5f %.5f" % n for n in vn) + "\n")
        f.write("\n".join(faces) + "\n")
    with open(out.with_suffix(".mtl"), "w") as f:
        f.write("# Pm = metallic, Pr = roughness (MTL PBR extension)\n" + "\n".join(mtl))


if __name__ == "__main__":
    main()
